CREATE TABLE points(
    id VARCHAR(50) PRIMARY KEY,
    name VARCHAR(100),
    x INT NOT NULL,
    y INT NOT NULL,
    floor INT NOT NULL,
    type VARCHAR(20) NOT NULL
);

CREATE TABLE edges(
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    node_a VARCHAR(50) NOT NULL,
    node_b VARCHAR(50) NOT NULL,
    weight FLOAT,
    FOREIGN KEY (node_a) REFERENCES points(id),
    FOREIGN KEY (node_b) REFERENCES points(id)
);

-- 2. Створення тригера для автоматичного розрахунку ваги (відстані в пікселях)
CREATE TRIGGER calculate_edge_weight
AFTER INSERT ON edges
FOR EACH ROW
WHEN NEW.weight IS NULL OR NEW.weight = 0
BEGIN
    UPDATE edges
    SET weight = ROUND(
        SQRT(
            ( (SELECT x FROM points WHERE id = NEW.node_a) - (SELECT x FROM points WHERE id = NEW.node_b) ) *
            ( (SELECT x FROM points WHERE id = NEW.node_a) - (SELECT x FROM points WHERE id = NEW.node_b) ) +
            ( (SELECT y FROM points WHERE id = NEW.node_a) - (SELECT y FROM points WHERE id = NEW.node_b) ) *
            ( (SELECT y FROM points WHERE id = NEW.node_a) - (SELECT y FROM points WHERE id = NEW.node_b) )
        ), 1)
    WHERE id = NEW.id;
END;

